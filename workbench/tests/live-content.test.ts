import { afterEach, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import { makeService, tmpDir, write, waitFor } from './helpers';
import { RootWatchers } from '../src/main/service/watcher';
import { LiveContentIndex } from '../src/main/backend/liveContent';

const cleanups: (() => Promise<void>)[] = [];
afterEach(async () => { while (cleanups.length) await cleanups.pop()!(); });
it('live watcher indexes appended/replaced/new/deleted/renamed content in the workbench DB', async () => {
  const indexer = await import('@kb/indexer');
  const { svc } = await makeService();
  const dir = tmpDir('live-content-');
  const note = path.join(dir, 'note.md');
  write(note, 'original words');
  const root = svc.addRoot(dir);
  await svc.scanRoot(root.id);
  indexer.migrate(svc.db);
  const live = new LiveContentIndex(svc, svc.db, indexer.indexOne, indexer.removeOne, 30);
  svc.on('fs-change', live.enqueue);
  const watchers = new RootWatchers(svc, 30);
  watchers.sync();
  cleanups.push(async () => { await watchers.closeAll(); svc.off('fs-change', live.enqueue); await live.close(); await indexer.closeIndexer(); await svc.close(); });
  await waitFor(() => svc.getIndexStatus().some(s => s.watching));
  const hits = (word: string) => indexer.searchGrouped(svc.db, word).hits;
  fs.appendFileSync(note, '\n琥珀续验词');
  await waitFor(() => hits('琥珀续验词').length === 1);
  fs.writeFileSync(note, 'original words');
  await waitFor(() => hits('琥珀续验词').length === 0);
  write(path.join(dir, 'new.md'), '翡翠新建词');
  await waitFor(() => hits('翡翠新建词').length === 1);
  fs.renameSync(path.join(dir, 'new.md'), path.join(dir, 'renamed.md'));
  await waitFor(() => hits('翡翠新建词')[0]?.relPath === 'renamed.md');
  fs.unlinkSync(path.join(dir, 'renamed.md'));
  await waitFor(() => hits('翡翠新建词').length === 0);
  expect(svc.db.prepare('SELECT COUNT(*) n FROM indexer_files').get()).toEqual({ n: 1 });
  expect(svc.db.prepare('SELECT COUNT(*) n FROM fts_content').get()).toEqual({ n: 1 });
}, 30000);

it('旁边文件连续写入时，外部改过的 md 仍会进索引，队列不超过上限', async () => {
  const indexer = await import('@kb/indexer');
  const { svc } = await makeService();
  const dir = tmpDir('live-queue-');
  const root = svc.addRoot(dir);
  await svc.scanRoot(root.id);
  indexer.migrate(svc.db);
  const live = new LiveContentIndex(svc, svc.db, indexer.indexOne, indexer.removeOne, 30);
  svc.on('fs-change', live.enqueue);
  const watchers = new RootWatchers(svc, 30);
  watchers.sync();
  cleanups.push(async () => { await watchers.closeAll(); svc.off('fs-change', live.enqueue); await live.close(); await indexer.closeIndexer(); await svc.close(); });
  await waitFor(() => svc.getIndexStatus().some(s => s.watching));
  const hits = (word: string) => indexer.searchGrouped(svc.db, word).hits;
  const target = path.join(dir, 'target.md');
  const spam = path.join(dir, 'spam.md');
  write(target, '队列外写词');
  await waitFor(() => hits('队列外写词').length === 1);
  write(spam, 'spam start');
  for (let i = 0; i < 400; i += 1) fs.appendFileSync(spam, `\n${i}`);
  fs.appendFileSync(target, '\n队列再写词');
  expect(watchers.queued()).toBeLessThanOrEqual(10000);
  await waitFor(() => hits('队列再写词').length === 1);
  expect(watchers.queued()).toBeLessThanOrEqual(10000);
}, 30000);
